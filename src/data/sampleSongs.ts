import { SamplePreset, MusicNote } from '../types';

function createNote(pitch: string, midi: number, start: number, duration: number, isMelody = true): MusicNote {
  return {
    id: `note-${start}-${midi}`,
    pitch,
    midiNumber: midi,
    startTime: start,
    duration,
    velocity: 90,
    isMelody,
  };
}

